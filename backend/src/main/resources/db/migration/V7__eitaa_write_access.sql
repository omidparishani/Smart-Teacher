--  V7 — دسترسی ارسال به کاربر (write access)
--
--  مسیر ب ارسال ایتا (پیام به کاربر خصوصی) تنها وقتی ممکن است که
--  کاربر با زدن «کلید شروع» یا باز کردن با لینک مستقیم به ما
--  دسترسی ارسال داده باشد (docs/eitaa.md بخش ۵.۲).
--
--  دو ستون لازم است، نه یکی:
--    • allows_write_to_pm     → وضعیت فعلی: آیا کاربر اجازه داده؟
--    • write_access_asked_at  → آیا تا حالا پرسیده‌ایم؟
--
--  ستون دوم برای سیاست محصولی است: «اگر کاربر رد کرد، هرگز دوباره
--  نپرس». بدون آن، هر ورود دوباره یک درخواست آزاردهنده می‌شود.
--  نمی‌شود از allows_write_to_pm = FALSE این را فهمید، چون «هنوز
--  نپرسیده‌ایم» و «پرسیده‌ایم و رد کرده» هر دو FALSE می‌دهند.
--
--  ⚠️ جدول eitaa_identities در V2 ساخته شده و هیچ تریگر
--  set_updated_at ندارد (فقط users و tenants دارند). پس مقدار
--  updated_at که Hibernate می‌نویسد دست‌نخورده می‌ماند.
--
--  ⚠️ آنچه عمداً اینجا نیست: جدول «لاگ پیام‌های خروجی».
--  ارسال به ایتا ردیابی می‌خواهد، اما طراحی آن در docs/database.md
--  با نام message_log و در فاز ۹ تعریف شده است. ساختن جدول
--  جایگزین در فاز ۲، همان چیزی را می‌سازد که §۸۰ خواسته‌ها از آن
--  نهی کرده: پیاده‌سازی زودهنگام بدون تست متناظر.
--  در فاز ۲ نتیجه ارسال از EitaaSendResult به فراخوان برمی‌گردد.
-- ═══════════════════════════════════════════════════════════

ALTER TABLE eitaa_identities
    ADD COLUMN allows_write_to_pm    BOOLEAN     NOT NULL DEFAULT FALSE,
    ADD COLUMN write_access_asked_at TIMESTAMPTZ NULL;

COMMENT ON COLUMN eitaa_identities.allows_write_to_pm IS
    'آیا کاربر به ما اجازه ارسال پیام خصوصی داده است (allows_write_to_pm در initData)';

COMMENT ON COLUMN eitaa_identities.write_access_asked_at IS
    'زمان آخرین درخواست requestWriteAccess — برای اینکه هرگز دوباره پرسیده نشود';
