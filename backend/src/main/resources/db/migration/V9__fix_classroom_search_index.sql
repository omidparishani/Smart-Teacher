--  ویرایش V8 یعنی تغییر checksum و در نتیجه شکست
--  Flyway validation در `mvn spring-boot:run` — خطایی که
--  ربطی به کار کاربر ندارد و رفعش (`flyway repair`) هم
--  واضح نیست. عدد جدید، مسیر بی‌دردسر است.
