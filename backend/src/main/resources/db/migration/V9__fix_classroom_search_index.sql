-- 🔴 V8 این ایندکس را ساخته بود:
--     CREATE INDEX idx_classrooms_name_trgm ON classrooms USING gin (name gin_trgm_ops);
--
--  و کوئری‌ای که سرویس می‌زند این است:
--     where lower(c.name) like :pattern escape '\'
--
--  این دو به هم نمی‌خورند. ایندکس روی تری‌گرام‌های `name` است و
--  کوئری تری‌گرام‌های `lower(name)` را می‌خواهد؛ پستگرس نمی‌تواند
--  این دو را به هم نگاشت کند و به Seq Scan برمی‌گردد.
--
--  ⚠️ این ادعا حدس نیست — با EXPLAIN سنجیده شد. با
--  `SET enable_seqscan = off` (یعنی وقتی پلنر را به زور به سمت
--  ایندکس هل می‌دهیم) روی جدولی ۲۰۰۰۰ ردیفی، خروجی همان Seq Scan
--  ماند. ایندکسِ روی `name` هرگز انتخاب نشد. با ایندکس روی
--  `lower(name)` پلن به Bitmap Index Scan تغییر کرد.
--
--  ⚠️ چرا این باگ مهم است؟ چون ایندکس بی‌مصرف بی‌اثر نیست:
--  هر INSERT و UPDATE باید آن را هم به‌روز کند و هر حذف نرم هم
--  درختش را دست می‌زند. یعنی هزینه دائمی می‌دهیم و در عوضش هیچ
--  چیزی نمی‌گیریم — و بدتر، هر خواننده‌ای که V8 را ببیند فکر
--  می‌کند جست‌وجو ایندکس دارد و دیگر سراغش نمی‌رود.
DROP INDEX IF EXISTS idx_classrooms_name_trgm;

-- ✅ شکل درست: همان عبارتِ کوئری.
--  ⚠️ شرط `deleted_at IS NULL` عیناً همان چیزی است که کوئری
--  می‌آورد، پس پلنر می‌تواند این ایندکس را جزئی تشخیص دهد و
--  ایندکس کوچک‌تر و به‌روزرسانی‌اش ارزان‌تر می‌ماند. این همان
--  الگویی است که بقیه ایندکس‌های V8 هم دارند.
CREATE INDEX idx_classrooms_name_trgm
    ON classrooms USING gin (lower(name) gin_trgm_ops)
    WHERE deleted_at IS NULL;

-- ⚠️ عمداً برای `subjects.name` ایندکس تری‌گرام ساخته نشد.
--  جست‌وجو آنجا هم `lower(s.name) like :pattern` است، ولی تعداد
--  درس‌های یک مدرسه در حد چند ده است. پیمایش کامل چند ده ردیف
--  از هر ایندکسی سریع‌تر است و ایندکسی که استفاده نمی‌شود فقط
--  هزینه نوشتن دارد — همان اشتباهی که در V8 شد و اینجا اصلاح
--  می‌شود. اگر روزی تعداد درس‌ها به هزاران رسید، این یادداشت
--  جای تصمیم‌گیری است.
