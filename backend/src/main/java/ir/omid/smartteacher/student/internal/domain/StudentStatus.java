package ir.omid.smartteacher.student.internal.domain;

/**
 * وضعیت دانش‌آموز.
 *
 * <p>⚠️ این enum با {@code chk_students_status} در مهاجرت {@code V10}
 * جور است. اگر مقدار تازه‌ای اضافه شد، <b>هر دو</b> باید عوض شوند —
 * وگرنه یا سرویس مقداری می‌فرستد که دیتابیس ردش می‌کند (خطای ۵۰۰ به‌جای
 * پیام روشن)، یا دیتابیس مقداری را می‌پذیرد که سرویس هرگز نمی‌فرستد.
 */
public enum StudentStatus {

    /** دانش‌آموز جاری — پیش‌فرض هنگام ساخت. */
    ACTIVE,

    /** موقتاً غیرفعال — مثلاً مرخصی یا انتقالی که ممکن است برگردد. */
    INACTIVE,

    /**
     * فارغ‌التحصیل.
     *
     * <p>⚠️ این وضعیت دانش‌آموز را <i>حذف نمی‌کند</i>: کارنامه و
     * سوابقش باید بماند. تفاوتش با {@code INACTIVE} معنایی است —
     * فارغ‌التحصیل برنمی‌گردد، غیرفعال ممکن است.
     */
    GRADUATED
}
