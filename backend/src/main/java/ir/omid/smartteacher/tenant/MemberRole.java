package ir.omid.smartteacher.tenant;

/**
 * نقش کاربر <b>در یک مستأجر مشخص</b> ({@code tenant_members.role}).
 *
 * <p><b>⚠️ این با نقش‌های سطح پلتفرم ({@code roles} در V3) یکی نیست.</b>
 * دو سیستم نقش موازی وجود دارد و خلط‌کردنشان خطای امنیتی است:
 * <ul>
 *   <li>{@code roles}/{@code user_roles} → دسترسی سطح پلتفرم
 *       (SUPER_ADMIN، ADMIN). به هیچ مستأجری گره نخورده‌اند.</li>
 *   <li>{@code tenant_members.role} (همین enum) → جایگاه کاربر داخل
 *       یک مستأجر. یک کاربر می‌تواند در مدرسه الف TEACHER و در
 *       مدرسه ب STUDENT باشد.</li>
 * </ul>
 *
 * <p>مجوز نهایی از <b>اشتراک</b> این دو به‌دست می‌آید، نه از یکی.
 */
public enum MemberRole {

    /** مالک مستأجر — دسترسی کامل، از جمله حذف مستأجر. */
    OWNER,

    /** مدیر مدرسه — مدیریت کاربران و کلاس‌ها، بدون تغییر مالکیت. */
    SCHOOL_ADMIN,

    /** معلم — ساخت کلاس، تکلیف، آزمون و استفاده از هوش مصنوعی. */
    TEACHER,

    /** دستیار معلم — کمک در تصحیح، بدون دسترسی به تنظیمات. */
    ASSISTANT,

    /** دانش‌آموز — شرکت در آزمون و ارسال تکلیف. */
    STUDENT
}
