package ir.omid.smartteacher.tenant;

/**
 * وضعیت عضویت یک کاربر در یک مستأجر — مطابق {@code chk_tm_status} در V2.
 *
 * <p><b>چرا {@code REMOVED} به‌جای حذف ردیف؟</b> چون تاریخچه عضویت
 * بخشی از سابقه آموزشی است: تکالیف و نمراتِ ارسال‌شده در آن مستأجر به
 * این کاربر گره خورده‌اند. حذف ردیف یعنی از دست دادن ردپای حسابرسی.
 */
public enum MemberStatus {

    /** عضو فعال — دسترسی کامل مطابق نقش. */
    ACTIVE,

    /** دعوت‌شده — هنوز دعوت را نپذیرفته، دسترسی ندارد. */
    INVITED,

    /** معلق — موقتاً دسترسی ندارد، عضویت حفظ می‌شود. */
    SUSPENDED,

    /** حذف‌شده — دسترسی ندارد، ردیف برای تاریخچه می‌ماند. */
    REMOVED
}
