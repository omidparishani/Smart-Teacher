package ir.omid.smartteacher.common.api;

import java.util.Locale;

/**
 * ساخت الگوی {@code LIKE} برای جست‌وجوی متنی.
 *
 * <p><b>🔴 چرا این کلاس لازم است؟</b> چون رشته‌ای که کاربر می‌فرستد
 * نمی‌تواند مستقیم داخل الگو بنشیند:
 * <ul>
 *   <li>{@code %} و {@code _} در {@code LIKE} نویسه عام هستند. کاربری
 *       که {@code %} می‌فرستد، به‌جای جست‌وجو، <i>همه</i> رکوردها را
 *       برمی‌گرداند — که هم غافلگیرکننده است و هم ایندکس trigram را
 *       بی‌اثر می‌کند.</li>
 *   <li>نویسه فرار خودش هم باید فرار داده شود، وگرنه ورودی
 *       {@code \\%} الگو را می‌شکند.</li>
 * </ul>
 *
 * <p>پس ترتیب کار مهم است: <b>اول</b> نویسه فرار، <b>بعد</b> عام‌ها.
 * اگر جای این دو عوض شود، بک‌اسلش‌هایی که خودمان اضافه کرده‌ایم دوباره
 * فرار داده می‌شوند و الگو خراب می‌شود.
 *
 * <p>⚠️ نویسه فرار {@code \} است و کوئری‌ها باید {@code escape '\\'}
 * داشته باشند. اگر کوئری‌ای این شرط را نداشته باشد، پستگرس بک‌اسلش را
 * جدی نمی‌گیرد و جست‌وجو بی‌صدا اشتباه می‌شود.
 *
 * <p><b>⚠️ چرا در {@code common.api} است و نه داخل یک ماژول دامنه؟</b>
 * چون این یک قاعده امنیتی است، نه منطق یک دامنه. جای اولش داخل
 * {@code classroom} بود؛ با آمدن {@code student} دو راه ماند: کپی‌کردن
 * (که یعنی دو نسخه از یک قاعده امنیتی که روزی از هم جدا می‌شوند) یا
 * بردنش به {@code common} (که یعنی یک نسخه برای همه). کنار
 * {@link PageableFactory} می‌نشیند چون هر دو یک کار می‌کنند: تبدیل
 * ورودی کاربر به چیزی که امن داخل کوئری بنشیند.
 */
public final class SearchPattern {

    /** نویسه فرار — باید با {@code escape} در کوئری جور باشد. */
    private static final String ESCAPE = "\\";

    private SearchPattern() {
        throw new AssertionError("کلاس ابزار نباید نمونه‌سازی شود");
    }

    /**
     * تبدیل ورودی کاربر به الگوی امن.
     *
     * @param raw ورودی خام کاربر؛ ممکن است {@code null} باشد
     * @return الگوی آماده مثل {@code %ریاضی%}، یا {@code null} اگر
     *         ورودی خالی بود — و {@code null} یعنی «بدون فیلتر»
     */
    public static String like(String raw) {
        if (raw == null || raw.isBlank()) {
            return null;
        }

        String escaped = raw.trim()
                .replace(ESCAPE, ESCAPE + ESCAPE)
                .replace("%", ESCAPE + "%")
                .replace("_", ESCAPE + "_");

        // ⚠️ Locale.ROOT و نه بدون آرگومان. در زبان ترکی، toLowerCase
        // حرف «I» را به «ı» تبدیل می‌کند و جست‌وجوهای لاتین بی‌صدا
        // خراب می‌شوند. این پروژه فارسی است ولی کد درس‌ها لاتین‌اند.
        return "%" + escaped.toLowerCase(Locale.ROOT) + "%";
    }
}
