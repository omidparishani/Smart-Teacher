package ir.omid.smartteacher.common.error;

/**
 * همان {@code initData} پیش‌تر مصرف شده است
 * ({@code docs/eitaa.md} بخش ۷.۴).
 *
 * <p><b>چرا لازم است، در حالی که پنجره پنج‌دقیقه‌ای هم هست؟</b> چون
 * آن دو، دو چیز متفاوت را می‌گیرند: بررسی {@code auth_date} پنجره را
 * محدود می‌کند، ولی <i>در همان پنجره</i> یک {@code initData} را
 * می‌شود چند بار فرستاد. هر بار یک نشست تازه می‌گیرد. این بررسی جلوی
 * همان را می‌گیرد.
 *
 * <p><b>⚠️ پیامد عملیاتی که باید بدانید:</b> ارسال دوباره همان
 * {@code initData} — مثلاً وقتی کلاینت درخواست را تکرار می‌کند — هم رد
 * می‌شود. این عمدی است: تفکیک «تکرار بی‌گناه» از «بازپخش حمله» در
 * سمت سرور ناممکن است. به‌جایش پیام به کاربر می‌گوید برنامک را دوباره
 * باز کند تا {@code initData} تازه بسازد — که هم کاربر عادی را نجات
 * می‌دهد و هم مهاجم را دست‌خالی برمی‌گرداند.
 */
public class EitaaInitDataReplayedException extends EitaaInitDataException {

    public EitaaInitDataReplayedException() {
        super("این نشست قبلاً استفاده شده است. برنامک را دوباره باز کنید.");
    }
}
