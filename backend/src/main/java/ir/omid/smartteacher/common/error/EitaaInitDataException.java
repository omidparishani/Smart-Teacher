package ir.omid.smartteacher.common.error;

/**
 * پایه همه شکست‌های اعتبارسنجی {@code initData} ایتا
 * ({@code docs/eitaa.md} بخش ۷).
 *
 * <p><b>⚠️ چرا سه زیرکلاس و نه یک کلاس با کد وضعیت متفاوت؟</b>
 * <ul>
 *   <li><b>برای تست:</b> «امضا نامعتبر است» با «قدیمی است» و «تکراری
 *       است» سه خرابی متفاوت‌اند و آزمون‌های بخش ۱۳ باید بتوانند
 *       تفکیکشان کنند. تستی که فقط هر سه را «۴۰۱» ببیند، اگر تشخیص
 *       انقضا بیفتد هم سبز می‌ماند.</li>
 *   <li><b>برای امنیت:</b> همه‌شان همان {@code ErrorCode} و همان
 *       وضعیت HTTP را برمی‌گردانند، پس تفکیک درونی به بیرون نشت
 *       نمی‌کند.</li>
 * </ul>
 *
 * <p><b>چه چیزی امن است افشا شود؟</b> پیام «منقضی» و «تکراری» فقط پس
 * از گذشتن از بررسی HMAC قابل مشاهده‌اند. یعنی کسی که این پیام‌ها را
 * می‌بیند، از قبل یک initData با امضای معتبر در دست داشته — و بدون
 * توکن ربات نمی‌شود چنین چیزی ساخت. پس افشای آن‌ها اطلاعاتی به مهاجم
 * نمی‌دهد و به کاربر می‌گوید چه کار کند.
 *
 * <p>در مقابل، «امضا نامعتبر است» هرگز نباید بگوید <i>کدام</i> بخش
 * خراب بود.
 */
public abstract class EitaaInitDataException extends AppException {

    protected EitaaInitDataException(String message) {
        super(ErrorCode.EITAA_INIT_DATA_INVALID, message);
    }
}
