package ir.omid.smartteacher.eitaa;

import java.time.Duration;

/**
 * نگه‌بان ضدبازپخش برای {@code initData}.
 *
 * <p><b>چرا اینترفیس است و نه فقط یک کلاس؟</b> چون نگه‌داری وضعیت،
 * وابسته به زیرساخت است: این نسخه در حافظه است و در فاز ۱۲ به Redis
 * منتقل می‌شود ({@code docs/roadmap.md}). اینترفیس باعث می‌شود آن
 * انتقال، تغییر پیاده‌سازی باشد نه تغییر {@link EitaaInitDataValidator}.
 *
 * <p><b>⚠️ محدودیت نسخه فعلی — پنهان نمی‌شود:</b> پیاده‌سازی حافظه‌ای
 * <b>فقط در یک نمونه</b> کار می‌کند. اگر برنامه روی چند نمونه اجرا شود،
 * دو درخواست یکسان که به دو نمونه مختلف برسند، هر دو پذیرفته می‌شوند.
 * این یک تخفیف واقعی است، نه یک جزئیات داخلی. با یک نمونه در فاز ۲
 * مشکلی ایجاد نمی‌کند و در فاز ۱۲ با Redis برطرف می‌شود.
 */
public interface ReplayGuard {

    /**
     * ثبت استفاده از یک اثر انگشت.
     *
     * @param fingerprint هش یکتای {@code initData}
     * @param window      مدت زمانی که این اثر انگشت باید به‌خاطر بماند
     * @return {@code true} اگر این نخستین استفاده باشد؛ {@code false} اگر
     *         همین اثر انگشت قبلاً و در همین پنجره ثبت شده باشد
     */
    boolean markUsed(String fingerprint, Duration window);

    /**
     * پاک‌کردن رکوردهای منقضی.
     *
     * <p>جدا از {@link #markUsed} نگه داشته شده تا اجرای دوره‌ای‌اش با
     * آزمون قابل کنترل باشد.
     *
     * @return تعداد رکوردهای پاک‌شده
     */
    int purgeExpired();
}
