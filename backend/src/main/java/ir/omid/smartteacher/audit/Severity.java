package ir.omid.smartteacher.audit;

/**
 * درجه اهمیت یک رویداد حسابرسی — مطابق {@code chk_audit_severity} در V5.
 *
 * <p>تفکیک درجه از روی «نوع رویداد» به‌دست می‌آید، نه سلیقه: درجه
 * تعیین می‌کند چه چیزی باید در پایش هشدار بدهد. هر رویداد امنیتی
 * حداقل {@link #WARNING} است.
 */
public enum Severity {

    /** عملیات عادی — ثبت می‌شود تا ردپا بماند، هشدار نمی‌دهد. */
    INFO,

    /** مشکوک — نیازمند بررسی دوره‌ای. */
    WARNING,

    /** رویداد امنیتی — باید فوراً بررسی شود. */
    CRITICAL
}
