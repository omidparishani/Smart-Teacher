package ir.omid.smartteacher.classroom.internal.domain;

/**
 * وضعیت چرخه عمر یک کلاس.
 *
 * <p><b>⚠️ چرا فقط دو مقدار؟</b> چون حالت‌های بیشتری که به ذهن می‌رسد
 * («در حال ثبت‌نام»، «تمام‌شده») در واقع وضعیت <i>سال تحصیلی</i> است،
 * نه کلاس؛ و سال تحصیلی همین حالا یک ستون جدا ({@code academic_year})
 * دارد. دو منبع حقیقت برای یک مفهوم، همان چیزی است که بعداً کسی را
 * وادار می‌کند بپرسد «کدامش درست است؟».
 *
 * <p>پس فقط یک تفاوت می‌ماند که کلاس در سال جاری هم نمی‌تواند بیانش
 * کند: «این کلاس دیگر فعال نیست». آن یکی {@link #ARCHIVED} است.
 */
public enum ClassRoomStatus {

    /** کلاس در جریان است و در فهرست پیش‌فرض معلم دیده می‌شود. */
    ACTIVE,

    /**
     * کلاس بایگانی شده — داده‌هایش می‌ماند ولی از فهرست کاری خارج است.
     *
     * <p>تفاوتش با حذف نرم ({@code deleted_at}) این است که بایگانی
     * <i>قابل برگشت</i> است و کلاس همچنان در گزارش‌های گذشته دیده
     * می‌شود؛ حذف نرم یعنی «این کلاس دیگر وجود ندارد».
     */
    ARCHIVED
}
